export const LOCALES = ["zh", "en", "ko", "ja"] as const;
export type Locale = (typeof LOCALES)[number];

export const LOCALE_COOKIE = "pj_lang";

export function localeCookie(locale: Locale): string {
  const secure = Boolean(process.env.VERCEL);
  return `${LOCALE_COOKIE}=${locale}; Path=/; Max-Age=${60 * 60 * 24 * 365}; SameSite=Lax${secure ? "; Secure" : ""}`;
}
export const LOCALE_LABEL: Record<Locale, string> = {
  zh: "中文",
  en: "EN",
  ko: "한국어",
  ja: "日本語",
};

export function isLocale(value: string | undefined): value is Locale {
  return LOCALES.includes(value as Locale);
}

export function parseLocale(raw?: string | null): Locale {
  const v = raw?.trim().toLowerCase() ?? "";
  if (v.startsWith("en")) return "en";
  if (v.startsWith("ko") || v.startsWith("kr")) return "ko";
  if (v.startsWith("ja") || v.startsWith("jp")) return "ja";
  if (v.startsWith("zh")) return "zh";
  return "zh";
}

export function htmlLang(locale: Locale): string {
  return { zh: "zh-CN", en: "en", ko: "ko", ja: "ja" }[locale];
}

